import JSZip from 'jszip';

/**
 * Arquivos sintéticos no formato que o Bambu Studio grava (2.x).
 * Servem até termos arquivos reais em samples/ — ver samples.test.ts.
 */

type FilamentFx = { id: number; type: string; color: string; usedG: string };
type PlateFx = { index: number; prediction?: string; weight?: string; filaments: FilamentFx[] };

export function sliceInfoXml(plates: PlateFx[]): string {
  const body = plates
    .map((p) => {
      const meta = [
        `    <metadata key="index" value="${p.index}"/>`,
        `    <metadata key="extruder_type" value="0"/>`,
        `    <metadata key="printer_model_id" value="N2S"/>`,
        `    <metadata key="nozzle_diameters" value="0.4"/>`,
        p.prediction != null ? `    <metadata key="prediction" value="${p.prediction}"/>` : '',
        p.weight != null ? `    <metadata key="weight" value="${p.weight}"/>` : '',
        `    <metadata key="outside" value="false"/>`,
        `    <metadata key="support_used" value="false"/>`,
        `    <object identify_id="${100 + p.index}" name="peca_${p.index}.stl" skipped="false" />`,
      ].filter(Boolean);
      const fils = p.filaments.map(
        (f) =>
          `    <filament id="${f.id}" tray_info_idx="GFA00" type="${f.type}" color="${f.color}" used_m="1.00" used_g="${f.usedG}" used_for_object="true" used_for_support="false" />`,
      );
      return ['  <plate>', ...meta, ...fils, '    <warning msg="bed_temperature_too_high_than_filament" level="1" error_code ="1000C001"  />', '  </plate>'].join('\n');
    })
    .join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header>
    <header_item key="X-BBL-Client-Type" value="slicer"/>
    <header_item key="X-BBL-Client-Version" value="02.02.00.85"/>
  </header>
${body}
</config>
`;
}

type GcodeFx = {
  weight: string;
  model: string;
  total: string;
  types: string;
  colors: string;
  costs: string;
  /** Linha "; filament: 1,3" (slots usados). */
  slots?: string;
  /** Linha "; filament_settings_id = ..." */
  profiles?: string;
};

export function gcodeText(opts: GcodeFx): string {
  const optional = (line: string, value?: string) => (value == null ? '' : `${line}${value}\n`);
  return `; HEADER_BLOCK_START
; generated by BambuStudio 02.02.00.85
; model printing time: ${opts.model}; total estimated time: ${opts.total}
; total layer number: 210
; total filament length [mm] : 16107.53
; total filament volume [cm^3] : 38742.36
; total filament weight [g] : ${opts.weight}
; filament_density: 1.24
; filament_diameter: 1.75
; max_z_height: 42.00
${optional('; filament: ', opts.slots)}; HEADER_BLOCK_END

; CONFIG_BLOCK_START
; filament_colour = ${opts.colors}
; filament_cost = ${opts.costs}
${optional('; filament_settings_id = ', opts.profiles)}; filament_type = ${opts.types}
; layer_height = 0.2
; CONFIG_BLOCK_END

; EXECUTABLE_BLOCK_START
M73 P0 R134
G28
G1 X10 Y10 Z0.2 E1.0
`;
}

const CONTENT_TYPES = `<?xml version="1.0" encoding="UTF-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
 <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
 <Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/>
 <Default Extension="gcode" ContentType="text/x.gcode"/>
</Types>`;

const MODEL = `<?xml version="1.0" encoding="UTF-8"?>
<model unit="millimeter" xml:lang="en-US" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><resources/><build/></model>`;

async function zipOf(files: Record<string, string>): Promise<Uint8Array> {
  const zip = new JSZip();
  for (const [path, content] of Object.entries(files)) zip.file(path, content);
  return zip.generateAsync({ type: 'uint8array', compression: 'DEFLATE' });
}

const base = { '[Content_Types].xml': CONTENT_TYPES, '3D/3dmodel.model': MODEL };

/** Duas placas; a segunda com dois filamentos. Preço no perfil só para os slots 1 e 3. */
export function multiPlate(): Promise<Uint8Array> {
  return zipOf({
    ...base,
    'Metadata/slice_info.config': sliceInfoXml([
      { index: 1, prediction: '8040', weight: '48.60', filaments: [{ id: 1, type: 'PLA', color: '#000000FF', usedG: '48.60' }] },
      {
        index: 2,
        prediction: '3900',
        weight: '22.10',
        filaments: [
          { id: 2, type: 'PLA', color: '#FFFFFF', usedG: '15.00' },
          { id: 3, type: 'PETG', color: '#C12E1F', usedG: '7.10' },
        ],
      },
    ]),
    'Metadata/project_settings.config': JSON.stringify({
      filament_cost: ['120', '0', '95.5'],
      filament_type: ['PLA', 'PLA', 'PETG'],
      filament_settings_id: ['Bambu PLA Basic @BBL X1C', 'Bambu PLA Basic @BBL X1C', 'Generic PETG @BBL X1C'],
    }),
    'Metadata/plate_1.gcode': gcodeText({ weight: '48.60', model: '2h 8m 36s', total: '2h 14m 0s', types: 'PLA;PLA;PETG', colors: '#000000;#FFFFFF;#C12E1F', costs: '120;0;95.5' }),
    'Metadata/plate_2.gcode': gcodeText({ weight: '15.00,7.10', model: '1h 2m', total: '1h 5m 0s', types: 'PLA;PLA;PETG', colors: '#000000;#FFFFFF;#C12E1F', costs: '120;0;95.5' }),
  });
}

/** "Exportar arquivo fatiado da placa" da placa 3: só ela aparece. */
export function singlePlateExport(): Promise<Uint8Array> {
  return zipOf({
    ...base,
    'Metadata/slice_info.config': sliceInfoXml([
      { index: 3, prediction: '2700', weight: '12.34', filaments: [{ id: 1, type: 'PETG', color: '#1565C0', usedG: '12.34' }] },
    ]),
    'Metadata/plate_3.gcode': gcodeText({ weight: '12.34', model: '44m', total: '45m 0s', types: 'PETG', colors: '#1565C0', costs: '0' }),
  });
}

/** slice_info sem peso/tempo/filamento: tudo deve vir do cabeçalho do G-code. */
export function gcodeFallback(): Promise<Uint8Array> {
  return zipOf({
    ...base,
    'Metadata/slice_info.config': sliceInfoXml([{ index: 1, filaments: [] }]),
    'Metadata/plate_1.gcode': gcodeText({ weight: '17.38', model: '1h 29m 5s', total: '1h 35m 25s', types: 'PLA', colors: '#FFFFFF', costs: '89.9' }),
  });
}

/** slice_info corrompido e sem project_settings: G-code também é a reserva. */
export function corruptSliceInfo(): Promise<Uint8Array> {
  return zipOf({
    ...base,
    'Metadata/slice_info.config': '<config><plate><metadata key="index" value="1"',
    'Metadata/plate_1.gcode': gcodeText({ weight: '30.5', model: '1h', total: '1d 2h 3m 4s', types: 'ABS', colors: '#F57C00', costs: '0' }),
  });
}

/** Projeto salvo sem fatiar: tem modelo e configs, mas nenhum consumo. */
export function unsliced(): Promise<Uint8Array> {
  return zipOf({
    ...base,
    'Metadata/model_settings.config': '<?xml version="1.0" encoding="UTF-8"?><config><plate><metadata key="plater_id" value="1"/></plate></config>',
    'Metadata/slice_info.config': sliceInfoXml([]),
    'Metadata/project_settings.config': JSON.stringify({ filament_cost: ['120'] }),
  });
}

/** ZIP qualquer, que não é .3mf. */
export function randomZip(): Promise<Uint8Array> {
  return zipOf({ 'leia-me.txt': 'oi' });
}
